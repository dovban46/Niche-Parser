    def segment_script(
        self,
        script: str,
        glossary: str = "",
        accent_tags: list[str] | None = None,
        ambience_tags: list[str] | None = None,
    ) -> list[SegmentPlan]:
        # "low" — це механічна задача (різати по межах речень і коротко тегувати), а не
        # творче письмо; саме на ній модель раніше спалила весь бюджет на роздуми (див.
        # коментар біля _MAX_TOKENS_SCRIPT). Глибокий reasoning тут не потрібен.
        accents, beds = accent_tags or [], ambience_tags or []
        system = _segment_system_prompt(accents, beds)
        chunks = _split_chunks(script, _SEGMENT_CHUNK_WORDS)

        segments: list[SegmentPlan] = []
        prior_shots: list[str] = []  # "shot" з попередніх частин — щоб наступні не повторювали ту саму композицію
        pause_count = 0  # скільки пауз-дихання вже поставлено — щоб не розсипати їх по кожному шматку окремо
        for i, chunk in enumerate(chunks, start=1):
            user = f"Візуальний глосарій:\n{glossary or '(немає)'}\n\nЧастина {i} з {len(chunks)} сценарію:\n{chunk}"
            if prior_shots:
                recent = "\n".join(f"- {s}" for s in prior_shots[-14:])
                user += (
                    "\n\nКАДРИ, ЩО ВЖЕ БУЛИ в попередніх частинах (не повторюй ці композиції — інший об'єкт "
                    f"у фокусі, інший план/ракурс/місце, навіть якщо тема сцени схожа):\n{recent}"
                )
            user += f"\n\nПАУЗ-ДИХАННЯ ВЖЕ ПОСТАВЛЕНО В ЦЬОМУ СЦЕНАРІЇ: {pause_count}. Якщо вже 3-4 — більше не став."
            data = _extract_json(self._complete(system, user, _MAX_TOKENS_SCRIPT, effort="low"))
            if isinstance(data, list):
                prior_shots.extend(str(item.get("shot", "")).strip() for item in data if item.get("shot"))
            if not isinstance(data, list):
                raise ProviderConfigError("Claude повернув не список сегментів — неочікуваний формат відповіді.")
            for item in data:
                text = str(item.get("text", "")).strip()
                pause_s = item.get("pause_seconds")
                pause_seconds = float(pause_s) if isinstance(pause_s, (int, float)) and pause_s and not text else 0.0
                if not text and not pause_seconds:
                    continue  # порожній сегмент без паузи — сміття, а не свідома пауза-дихання
                shot = str(item.get("shot", "")).strip()
                keywords = str(item.get("visual_keywords", "")).strip() or " ".join(shot.split()[:5])
                sfx_tags = [t for t in (item.get("sfx") or []) if t in accents][:2]
                ambience = str(item.get("ambience", "")).strip()
                is_pause = pause_seconds > 0
                if is_pause:
                    pause_count += 1
                plan = SegmentPlan(
                    text=text,
                    visual_keywords=keywords,
                    suggested_source="generated",
                    shot=shot or keywords,
                    motion=str(item.get("motion", "")).strip() or "slow camera push-in, gentle wind",
                    # Пауза-дихання — завжди анімована: єдиний носій уваги тут картинка+звук, без диктора.
                    visual_type="animated" if (is_pause or item.get("visual_type") == "animated") else "still",
                    sfx=sfx_tags,
                    ambience=ambience if ambience in beds else "",
                    cta=bool(item.get("cta")),
                )
                if is_pause:
                    plan["pause_seconds"] = min(pause_seconds, 5.0)
                segments.append(plan)
        # Перші 3 сегменти — завжди анімовані й підсилено деталізовані (фідбек 2026-09-29): це вступ теми,
        # головний гачок глядача, ціна тут виправдана незалежно від MAX_ANIMATED_SHARE для решти відео.
        for i, seg in enumerate(segments[:3]):
            seg["visual_type"] = "animated"
            hook_shot = seg.get("shot", "")
            if hook_shot:
                seg["shot"] = (
                    hook_shot + ", exceptionally detailed and atmospheric shot, among the most visually "
                    "important frames of the video, worth extra richness"
                )
        return segments

    def expand_shot_beats(self, shot: str, glossary: str, n: int) -> list[str]:
        user = (
            f"Візуальний глосарій: {glossary or '(немає)'}\n\nБазовий кадр (одна сцена/тема): {shot}\n\n"
            f"Дай РІВНО {n} варіантів кадру для генератора картинок."
        )
        raw = self._complete(_BEATS_SYSTEM_PROMPT.format(n=n), user, 2000, effort="low")
        data = _extract_json(raw)
        if not isinstance(data, list) or not data:
            return [shot] * n
        out = [str(x).strip() for x in data if str(x).strip()][:n]
        while len(out) < n:
            out.append(out[-1] if out else shot)
        return out

    def judge_image(self, image_path, scene: str, style_desc: str) -> dict | None:
        try:
            from PIL import Image
            img = Image.open(image_path).convert("RGB")
            img.thumbnail((640, 360))
            buf = io.BytesIO()
            img.save(buf, format="JPEG", quality=80)
            data = base64.b64encode(buf.getvalue()).decode()
            model = os.environ.get("JUDGE_MODEL") or "claude-haiku-4-5-20251001"
            response = self._client.messages.create(
                model=model, max_tokens=200, system=_JUDGE_SYSTEM_PROMPT,
                messages=[{"role": "user", "content": [
                    {"type": "image", "source": {"type": "base64", "media_type": "image/jpeg", "data": data}},
                    {"type": "text", "text": f"REQUIRED STYLE: {style_desc}\nREQUIRED SCENE: {scene[:600]}"},
                ]}],
            )
            usage_tracker.record("claude-haiku-4-5", response.usage.input_tokens, response.usage.output_tokens)
            text = "".join(b.text for b in response.content if b.type == "text")
            verdict = _extract_json(text)
            return {"style_ok": bool(verdict.get("style_ok")), "scene_ok": bool(verdict.get("scene_ok")),
                    "why": str(verdict.get("why", ""))[:120]}
        except Exception:  # контролер — допоміжний: його збій не повинен валити генерацію кадрів
            return None

