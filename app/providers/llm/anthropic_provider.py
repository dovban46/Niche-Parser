def _dossier_check(dossier: str) -> str:
    if not dossier:
        return ""
    return (
        "\n\nДОСЬЄ ТЕМИ (затверджене автором): звір сценарій із ним — факти, спорядження, тактика й технології мають "
        "відповідати епосі та сторонам, без анахронізмів; виправ лише невідповідності, решту не чіпай.\n" + dossier
    )


